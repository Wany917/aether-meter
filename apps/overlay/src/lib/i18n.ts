const catalogs: Record<"fr" | "en", Record<MessageKey, string>> = { fr, en };

export type Translate = (key: MessageKey) => string;

/** French or English UI; every other game language gets the English UI. */
export function uiLocale(language: string): "fr" | "en" {
  return language === "fr" ? "fr" : "en";
}

export function translator(language: string): Translate {
  const catalog = catalogs[uiLocale(language)];
  return (key) => catalog[key];
}

